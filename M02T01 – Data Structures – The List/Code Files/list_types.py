# M02T01: Lists - Working with friend names and ages
# This program demonstrates creating lists and accessing elements

# Create a list of three friends' names
friends_names = ["Sophia Johnson", "Michael Brown", "Emma Williams"]

# Print the first friend
print("First friend:", friends_names[0])

# Print the last friend
print("Last friend:", friends_names[-1])

# Print the length of the list
print("Number of friends:", len(friends_names))

# Create a list of corresponding ages
friends_ages = [25, 28, 23]

# Print each friend's name and age in a sentence
print(f"{friends_names[0]} is {friends_ages[0]} years old")
print(f"{friends_names[1]} is {friends_ages[1]} years old")
print(f"{friends_names[2]} is {friends_ages[2]} years old")
