# M01T03: Variables Task 2 - Type Conversion
# This program demonstrates casting between different data types

# Declare the initial variables with their original types
num1 = 99.23
num2 = 23
num3 = 150
string1 = "100"

# Convert the variables to the specified types
num1 = int(num1)        # Convert num1 from float to integer
num2 = float(num2)      # Convert num2 from integer to float
num3 = str(num3)        # Convert num3 from integer to string
string1 = int(string1)  # Convert string1 from string to integer

# Print all the converted variables on separate lines
print(num1)
print(num2)
print(num3)
print(string1)
